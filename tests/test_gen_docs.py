"""docs/as-built/ is what scripts/gen_docs.py writes, every time.

The generator is the only author of those files, and the `docs-fresh` CI job
fails on any diff between them and the commit, so the files are the
deliverable and reading them back is the point rather than a markup check:
what these tests protect is that the generator runs, that a second run writes
the same bytes, and that a route, a record kind and an event type the app
really has arrive on the pages.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / 'scripts' / 'gen_docs.py'
ROUTES = ROOT / 'docs' / 'as-built' / 'routes.md'
DATA = ROOT / 'docs' / 'as-built' / 'data.md'
LLM = ROOT / 'docs' / 'as-built' / 'llm.md'


def run_generator():
    """Run the generator the way a person and CI run it. It writes into this
    checkout on purpose: those files are the ones the docs-fresh job compares
    with the commit."""
    result = subprocess.run([sys.executable, str(GENERATOR)], cwd=ROOT,
                            capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stderr


def generate():
    run_generator()
    return ROUTES.read_bytes()


def generate_data():
    run_generator()
    return DATA.read_bytes()


def generate_llm():
    run_generator()
    return LLM.read_bytes()


def test_generator_runs_and_writes_the_routes_page():
    assert generate().startswith(b'GENERATED by scripts/gen_docs.py from ')


def test_a_second_run_writes_the_same_bytes():
    assert generate() == generate()


def test_the_jobs_routes_arrive_on_the_page():
    """One Flask rule and one React route, both of which the app has: the
    board's own path, and the endpoint its job list comes from."""
    page = generate().decode()
    assert '| `/api/jobs` | GET | `job_collection` |' in page
    assert '| `/jobs` | `JobsBoard` | My Jobs |' in page


def test_the_generator_writes_the_data_model_page_too():
    assert generate_data().startswith(b'GENERATED by scripts/gen_docs.py from ')


def test_a_second_run_writes_the_same_data_model_bytes():
    assert generate_data() == generate_data()


def test_the_data_model_the_app_really_has_arrives_on_the_page():
    """One record kind, one permissions row, one event type and both
    diagrams, each of which the app has: the job record and where it is
    stored, the endpoint the board's job list comes from with the kind it
    reads, the event every added job writes, and the two pictures."""
    page = generate_data().decode()
    assert '\n### jobs\n' in page
    assert '\n* Stored at: `jobs/`, one file per record,' in page
    assert '| `/api/jobs` | GET | `job_collection` | jobs | owner only |' in page
    assert '| `created` | `Job added` | visible |' in page
    assert 'stateDiagram-v2' in page
    assert 'erDiagram' in page


def test_the_generator_writes_the_model_page_too():
    assert generate_llm().startswith(b'GENERATED by scripts/gen_docs.py from ')


def test_a_second_run_writes_the_same_model_page_bytes():
    assert generate_llm() == generate_llm()


def test_what_the_app_really_sends_to_a_model_arrives_on_the_page():
    """One call site with the fields its prompt carries and where its request
    goes, one field no prompt carries, and the accounting row for the one
    function that opens the request: the four things the page exists for."""
    page = generate_llm().decode()
    assert '`careeros.ingest.build_prompt`' in page
    assert 'the posting description (record): jobs `description`' in page
    assert 'no (LAN) unless CLASSIFY_LLM_BASE_URL points elsewhere' in page
    assert '`salary`' in page.split('## Where text goes to a model')[0]
    assert '| `careeros.llm_client.LLMClient.create` | the transport:' in page
