"""docs/as-built/routes.md is what scripts/gen_docs.py writes, every time.

The generator is the only author of that file, and the `docs-fresh` CI job
fails on any diff between the two, so the file is the deliverable and reading
it back is the point rather than a markup check: what these tests protect is
that the generator runs, that a second run writes the same bytes, and that a
route the app really has arrives on the page.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / 'scripts' / 'gen_docs.py'
ROUTES = ROOT / 'docs' / 'as-built' / 'routes.md'


def generate():
    """Run the generator the way a person and CI run it, and read back what it
    wrote. It writes into this checkout on purpose: that file is the one the
    docs-fresh job compares with the commit."""
    result = subprocess.run([sys.executable, str(GENERATOR)], cwd=ROOT,
                            capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stderr
    return ROUTES.read_bytes()


def test_generator_runs_and_writes_the_routes_page():
    assert generate().startswith(b'GENERATED by scripts/gen_docs.py from ')


def test_a_second_run_writes_the_same_bytes():
    assert generate() == generate()


def test_the_jobs_routes_arrive_on_the_page():
    """One Flask rule and one React route, both of which the app has: the
    board's own path, and the endpoint its job list comes from."""
    page = generate().decode()
    assert '| `/api/jobs` | GET | `job_collection` |' in page
    assert '| `/jobs` | `JobsBoard` | My Jobs |' in page
